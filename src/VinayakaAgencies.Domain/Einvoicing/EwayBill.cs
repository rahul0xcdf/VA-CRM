using VinayakaAgencies.Domain.Common;

namespace VinayakaAgencies.Domain.Einvoicing;

/// <summary>
/// One e-way bill: Part-A captured from the invoice, Part-B carrying the transport details, and the
/// portal's number and validity once issued (phase-6-einvoice-eway.md §2).
/// </summary>
/// <remarks>
/// <para>
/// Part-A and Part-B are modelled as one row rather than two because the portal treats them that
/// way: a bill exists with Part-A filled and Part-B blank, and Part-B can be updated repeatedly
/// afterwards as the vehicle changes en route. Splitting them into separate entities would invent a
/// distinction the API does not have.
/// </para>
/// <para>
/// A bill may be generated either from an invoice directly or by IRN, and the two differ only in
/// what the portal is sent — hence <see cref="Irn"/> being nullable rather than there being two
/// entity types. Validity is stored as the instant it expires, computed once at generation from the
/// distance and vehicle type, because re-deriving it later from a changed distance would silently
/// move an expiry the portal has already fixed.
/// </para>
/// </remarks>
public sealed class EwayBill : Entity, IAuditStamped
{
    /// <summary>How long after generation an e-way bill may still be cancelled.</summary>
    public static readonly TimeSpan CancellationWindow = TimeSpan.FromHours(24);

    private EwayBill()
    {
        // EF Core materialisation.
    }

    public EwayBill(
        Guid companyId,
        Guid tradeDocumentId,
        long consignmentValueMinor,
        int distanceKilometres,
        string? irn = null)
    {
        if (companyId == Guid.Empty)
        {
            throw new ArgumentException("CompanyId must not be empty.", nameof(companyId));
        }

        if (tradeDocumentId == Guid.Empty)
        {
            throw new ArgumentException(
                "An e-way bill must name the document it moves.", nameof(tradeDocumentId));
        }

        if (consignmentValueMinor < 0)
        {
            throw new ArgumentOutOfRangeException(
                nameof(consignmentValueMinor),
                consignmentValueMinor,
                "A consignment value cannot be negative.");
        }

        if (distanceKilometres < 0)
        {
            throw new ArgumentOutOfRangeException(
                nameof(distanceKilometres),
                distanceKilometres,
                "A transport distance cannot be negative.");
        }

        if (irn is not null && !IrnFormula.IsWellFormed(irn))
        {
            throw new ArgumentException(
                "An e-way bill generated by IRN needs a well-formed 64-character IRN.", nameof(irn));
        }

        CompanyId = companyId;
        TradeDocumentId = tradeDocumentId;
        ConsignmentValueMinor = consignmentValueMinor;
        DistanceKilometres = distanceKilometres;
        Irn = irn;
        VehicleType = VehicleType.Regular;
        Status = EwayBillStatus.Draft;
    }

    public Guid CompanyId { get; private set; }

    /// <summary>The invoice or challan this bill moves.</summary>
    public Guid TradeDocumentId { get; private set; }

    /// <summary>Set when the bill is generated by IRN rather than straight from the invoice.</summary>
    public string? Irn { get; private set; }

    /// <summary>Consignment value in minor units of 1/10,000 (ADR-0003).</summary>
    public long ConsignmentValueMinor { get; private set; }

    /// <summary>Approximate distance, which fixes the bill's validity.</summary>
    public int DistanceKilometres { get; private set; }

    public EwayBillStatus Status { get; private set; }

    /// <summary>The portal's e-way bill number, once issued.</summary>
    public long? EwayBillNumber { get; private set; }

    public DateTimeOffset? GeneratedAtUtc { get; private set; }

    /// <summary>When the bill expires. Fixed at generation and only moved by an extension.</summary>
    public DateTimeOffset? ValidUntilUtc { get; private set; }

    // --- Part-B: transport details (phase-6 §4a) ---

    public TransportMode? TransportMode { get; private set; }

    public VehicleType VehicleType { get; private set; }

    public string? TransporterGstin { get; private set; }

    public string? TransporterName { get; private set; }

    public string? TransportDocumentNumber { get; private set; }

    public DateOnly? TransportDocumentDate { get; private set; }

    public string? VehicleNumber { get; private set; }

    public DateTimeOffset? CancelledAtUtc { get; private set; }

    public string? CancellationReasonCode { get; private set; }

    public string? CancellationRemarks { get; private set; }

    public string? LastErrorText { get; private set; }

    public DateTimeOffset CreatedAtUtc { get; set; }

    public string CreatedBy { get; set; } = string.Empty;

    public DateTimeOffset? ModifiedAtUtc { get; set; }

    public string? ModifiedBy { get; set; }

    /// <summary>True once Part-B carries enough detail for the mode chosen.</summary>
    public bool IsPartBComplete =>
        TransportMode is { } mode
        && mode switch
        {
            // By road the vehicle is what is checked at a barrier, so its number is the required field.
            Einvoicing.TransportMode.Road => !string.IsNullOrWhiteSpace(VehicleNumber),

            // Otherwise the carrier's own document identifies the consignment.
            _ => !string.IsNullOrWhiteSpace(TransportDocumentNumber) && TransportDocumentDate is not null,
        };

    /// <summary>True when the bill is issued and has not expired as at <paramref name="nowUtc"/>.</summary>
    public bool IsValidAt(DateTimeOffset nowUtc) =>
        Status is EwayBillStatus.Active && ValidUntilUtc is { } until && nowUtc <= until;

    /// <summary>True while the bill may still be cancelled at the portal.</summary>
    public bool CanCancelAt(DateTimeOffset nowUtc) =>
        Status is EwayBillStatus.Active
        && GeneratedAtUtc is { } generated
        && nowUtc <= generated + CancellationWindow;

    /// <summary>Records Part-B. Callable repeatedly — the vehicle genuinely does change en route.</summary>
    public void SetPartB(
        TransportMode transportMode,
        VehicleType vehicleType,
        string? vehicleNumber = null,
        string? transporterGstin = null,
        string? transporterName = null,
        string? transportDocumentNumber = null,
        DateOnly? transportDocumentDate = null)
    {
        if (transportMode is Einvoicing.TransportMode.Road && string.IsNullOrWhiteSpace(vehicleNumber))
        {
            throw new ArgumentException(
                "Road transport needs a vehicle number.", nameof(vehicleNumber));
        }

        if (transportMode is not Einvoicing.TransportMode.Road
            && (string.IsNullOrWhiteSpace(transportDocumentNumber) || transportDocumentDate is null))
        {
            throw new ArgumentException(
                "Rail, air and ship transport need a transport document number and date.",
                nameof(transportDocumentNumber));
        }

        TransportMode = transportMode;
        VehicleType = vehicleType;
        VehicleNumber = Normalise(vehicleNumber)?.ToUpperInvariant();
        TransporterGstin = Normalise(transporterGstin)?.ToUpperInvariant();
        TransporterName = Normalise(transporterName);
        TransportDocumentNumber = Normalise(transportDocumentNumber);
        TransportDocumentDate = transportDocumentDate;
    }

    /// <summary>Records the number and validity the portal issued.</summary>
    public void MarkGenerated(long ewayBillNumber, DateTimeOffset generatedAtUtc)
    {
        if (Status is EwayBillStatus.Cancelled)
        {
            throw new InvalidOperationException(
                "A cancelled e-way bill cannot be re-issued; generate a new one.");
        }

        EwayBillNumber = ewayBillNumber;
        GeneratedAtUtc = generatedAtUtc;
        ValidUntilUtc = EwayBillValidity.ExpiresAtUtc(
            generatedAtUtc, DistanceKilometres, VehicleType);
        LastErrorText = null;
        Status = EwayBillStatus.Active;
    }

    public void MarkRejected(string errorText)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(errorText);

        LastErrorText = errorText.Trim();
        Status = EwayBillStatus.Rejected;
    }

    public void MarkCancelled(
        DateTimeOffset cancelledAtUtc,
        string reasonCode,
        string? remarks = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(reasonCode);

        if (!CanCancelAt(cancelledAtUtc))
        {
            throw new InvalidOperationException(
                "An e-way bill can only be cancelled within 24 hours of generation.");
        }

        CancelledAtUtc = cancelledAtUtc;
        CancellationReasonCode = reasonCode.Trim();
        CancellationRemarks = Normalise(remarks);
        Status = EwayBillStatus.Cancelled;
    }

    /// <summary>
    /// Moves the expiry out after the portal accepted an extension. The portal decides the new
    /// expiry, so it is passed in rather than recomputed — an extension is granted, not calculated.
    /// </summary>
    public void MarkExtended(DateTimeOffset newValidUntilUtc, int remainingDistanceKilometres)
    {
        if (Status is not EwayBillStatus.Active)
        {
            throw new InvalidOperationException("Only an active e-way bill can be extended.");
        }

        if (remainingDistanceKilometres < 0)
        {
            throw new ArgumentOutOfRangeException(
                nameof(remainingDistanceKilometres),
                remainingDistanceKilometres,
                "A remaining distance cannot be negative.");
        }

        if (ValidUntilUtc is { } current && newValidUntilUtc < current)
        {
            throw new ArgumentException(
                "An extension cannot shorten an e-way bill's validity.", nameof(newValidUntilUtc));
        }

        ValidUntilUtc = newValidUntilUtc;
        DistanceKilometres = remainingDistanceKilometres;
    }

    private static string? Normalise(string? value) =>
        string.IsNullOrWhiteSpace(value) ? null : value.Trim();
}
